function wave(count: number, base: number, amplitude: number, drift = 0, jitter = 0.04): number[] {
  const out: number[] = [];
  let seed = 20261101;
  for (let i = 0; i < count; i += 1) {
    seed = (seed * 1103515245 + 12345) % 2147483648;
    const noise = (seed / 2147483648 - 0.5) * 2;
    const v = base + Math.sin((i / count) * Math.PI * 2.6) * amplitude + drift * (i / count) + noise * jitter * base + noise * amplitude * 0.35;
    out.push(Math.max(0, Number(v.toFixed(3))));
  }
  return out;
}

function series(name: string, unit: string, points: number[], labels: Record<string, string>): MetricSeries {
  const current = points[points.length - 1] ?? 0;
  return {
    name,
    unit,
    points,
    labels,
    current,
    min: Math.min(...points),
    max: Math.max(...points),
    avg: points.reduce((a, b) => a + b, 0) / Math.max(1, points.length),
  };
}

